//! Writes `docs/api.md`: every public function, method and type of dfui and
//! dfui-map with the first sentence of its docs, one line each, so a reader
//! (or an agent) can find what exists before writing it again. Its test fails
//! when the file is out of date.

use std::fmt::Write;
use std::path::{Path, PathBuf};

const CRATES: [(&str, &str); 2] = [("dfui", "src"), ("dfui-map", "map/src")];
const OUT: &str = "docs/api.md";
/// Types with `pub` methods for the crate's own use that the crate root
/// doesn't export.
const INTERNAL: [&str; 7] = [
    "Clipboard",
    "LoopWaker",
    "Outlines",
    "Renderer",
    "Ring",
    "Runtime",
    "Scene",
];

fn main() {
    std::fs::write(root().join(OUT), index()).expect(OUT);
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn index() -> String {
    let mut out = String::from(
        "# API index\n\nEvery public function, method and type, with the first sentence of its \
         docs. Generated by `cargo run -p api-index`; a test fails when it's out of date. \
         Look here before writing a helper: the docs of each item are on docs.rs and in the \
         source. Builder methods shared by all widgets are on `Styled`.\n",
    );
    for (name, dir) in CRATES {
        write!(out, "\n## {name}\n").unwrap();
        let mut files = Vec::new();
        rust_files(&root().join(dir), &mut files);
        files.sort();
        for f in files {
            let items = scan(&std::fs::read_to_string(&f).unwrap());
            if items.is_empty() {
                continue;
            }
            let rel = f
                .strip_prefix(root())
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/");
            write!(out, "\n### {rel}\n\n").unwrap();
            for (sig, doc) in items {
                match doc.is_empty() {
                    true => writeln!(out, "- `{sig}`").unwrap(),
                    false => writeln!(out, "- `{sig}`: {doc}").unwrap(),
                }
            }
        }
    }
    out
}

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    for e in std::fs::read_dir(dir).unwrap().flatten() {
        let p = e.path();
        if p.is_dir() {
            rust_files(&p, out);
        } else if p.extension().is_some_and(|x| x == "rs") && !p.ends_with("tests.rs") {
            out.push(p);
        }
    }
}

/// The public items of one rustfmt-formatted file: signature and first
/// doc sentence.
// ponytail: reads lines, not Rust; relies on rustfmt's layout and lists `pub`
// items of private modules too. Switch to rustdoc JSON once it's on stable.
fn scan(src: &str) -> Vec<(String, String)> {
    let lines: Vec<&str> = src.lines().collect();
    let mut items = Vec::new();
    let (mut doc, mut hidden) = (Vec::new(), false);
    // The type an `impl` or `trait` block at the top level is for.
    let mut owner: Option<(String, Block)> = None;
    for (i, line) in lines.iter().enumerate() {
        let t = line.trim();
        let indent = line.len() - line.trim_start().len();
        if indent == 0 && t == "#[cfg(test)]" {
            break;
        }
        if let Some(d) = t.strip_prefix("///") {
            doc.push(d.trim());
            continue;
        }
        if t.starts_with("#[") {
            hidden |= t.contains("doc(hidden)");
            continue;
        }
        if indent == 0 {
            if t == "}" {
                owner = None;
            } else if let Some(o) = block_owner(t) {
                owner = Some(o);
            }
        }
        let item = match (indent, &owner) {
            (0, _) if is_pub_item(t) => Some(signature(&lines[i..], None)),
            (4, Some((o, Block::Inherent)))
                if t.starts_with("pub fn ") || t.starts_with("pub const fn ") =>
            {
                Some(signature(&lines[i..], Some(o)))
            }
            (4, Some((o, Block::Trait))) if t.starts_with("fn ") => {
                Some(signature(&lines[i..], Some(o)))
            }
            _ => None,
        };
        let internal = |sig: &str| {
            INTERNAL
                .iter()
                .any(|t| sig.starts_with(&format!("{t}::")) || sig.ends_with(&format!(" {t}")))
        };
        if let (Some(sig), false) = (item, hidden)
            && !internal(&sig)
        {
            items.push((sig, first_sentence(&doc)));
        }
        (doc, hidden) = (Vec::new(), false);
    }
    items
}

fn is_pub_item(t: &str) -> bool {
    let kinds = ["fn ", "const fn ", "struct ", "enum ", "trait ", "type "];
    t.strip_prefix("pub ")
        .is_some_and(|r| kinds.iter().any(|k| r.starts_with(k)))
}

#[derive(Clone, Copy, PartialEq)]
enum Block {
    /// `impl Type`: its `pub fn`s are listed.
    Inherent,
    /// `pub trait`: all its methods are public.
    Trait,
    /// `impl Trait for Type`: documented on the trait.
    TraitImpl,
}

/// The type an `impl` or `pub trait` block is for, and which kind it is.
fn block_owner(t: &str) -> Option<(String, Block)> {
    if let Some(r) = t.strip_prefix("pub trait ") {
        return Some((ident(r), Block::Trait));
    }
    let r = skip_generics(t.strip_prefix("impl")?.trim_start());
    Some(match r.split_once(" for ") {
        Some((_, ty)) => (ident(ty), Block::TraitImpl),
        None => (ident(r), Block::Inherent),
    })
}

fn skip_generics(s: &str) -> &str {
    if !s.starts_with('<') {
        return s;
    }
    let mut depth = 0;
    for (i, c) in s.char_indices() {
        match c {
            '<' => depth += 1,
            '>' => depth -= 1,
            _ => {}
        }
        if depth == 0 {
            return s[i + 1..].trim_start();
        }
    }
    s
}

fn ident(s: &str) -> String {
    s.trim()
        .split(|c: char| !(c.is_alphanumeric() || c == '_'))
        .next()
        .unwrap_or_default()
        .to_owned()
}

/// The item's header joined onto one line, up to its body or `where`.
fn signature(lines: &[&str], owner: Option<&str>) -> String {
    let mut sig = String::new();
    for l in lines {
        let t = l.trim();
        if t.starts_with("where") {
            break;
        }
        sig.push_str(t);
        sig.push(' ');
        if t.ends_with('{') || t.ends_with(';') || t.ends_with("{}") {
            break;
        }
    }
    let sig = sig.trim().trim_end_matches(['{', ';', '}']).trim();
    let sig = sig
        .replace("( ", "(")
        .replace(", )", ")")
        .replace(" )", ")");
    let sig = sig
        .strip_prefix("pub ")
        .unwrap_or(&sig)
        .replace("mut self", "self");
    match owner {
        Some(o) => {
            let name = sig.trim_start_matches("const ");
            format!("{o}::{}", name.strip_prefix("fn ").unwrap_or(name))
        }
        None => sig,
    }
}

fn first_sentence(doc: &[&str]) -> String {
    let text = doc
        .iter()
        .take_while(|l| !l.is_empty())
        .copied()
        .collect::<Vec<_>>()
        .join(" ");
    // The first ". " that doesn't end an abbreviation.
    let end = text.match_indices(". ").map(|(i, _)| i).find(|&i| {
        !["e.g", "i.e", "etc", "vs"]
            .iter()
            .any(|a| text[..i].ends_with(a))
    });
    match end {
        Some(i) => text[..=i].to_owned(),
        None => text,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn index_is_current() {
        let saved = std::fs::read_to_string(root().join(OUT)).unwrap_or_default();
        assert!(
            saved == index(),
            "{OUT} is out of date: run `cargo run -p api-index`"
        );
    }

    #[test]
    fn scans_items_methods_and_trait_methods() {
        let src = "/// A label, e.g. a title. More.\npub fn text(s: &str) -> Label {\n}\n\
            impl Label {\n    /// Size.\n    pub fn size(mut self, s: f32) -> Self {\n    }\n    fn private() {}\n}\n\
            impl Widget for Label {\n    pub fn not_listed() {}\n}\n\
            pub trait Styled {\n    /// Grow.\n    fn grow(\n        self,\n        g: f32,\n    ) -> Self\n    where\n        Self: Sized,\n    {\n    }\n}\n\
            pub(crate) fn hidden() {}\n#[cfg(test)]\nmod tests {\n    pub fn t() {}\n}\n";
        let items = scan(src);
        let sigs: Vec<&str> = items.iter().map(|(s, _)| s.as_str()).collect();
        assert_eq!(
            sigs,
            [
                "fn text(s: &str) -> Label",
                "Label::size(self, s: f32) -> Self",
                "trait Styled",
                "Styled::grow(self, g: f32) -> Self"
            ]
        );
        assert_eq!(items[0].1, "A label, e.g. a title.");
    }
}
