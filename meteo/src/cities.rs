//! The cities shown, by region: the capital first, then the others in its
//! region. Regions are named as in the GISCO NUTS 2 data.

pub struct City {
    pub name: &'static str,
    pub region: &'static str,
    /// The region's capital, shown on the whole country's map.
    pub capital: bool,
    pub lat: f64,
    pub lon: f64,
    /// INE municipality code, AEMET's id; empty outside Spain.
    pub aemet: &'static str,
}

const fn capital(
    region: &'static str,
    name: &'static str,
    lat: f64,
    lon: f64,
    aemet: &'static str,
) -> City {
    City {
        name,
        region,
        capital: true,
        lat,
        lon,
        aemet,
    }
}

const fn town(
    region: &'static str,
    name: &'static str,
    lat: f64,
    lon: f64,
    aemet: &'static str,
) -> City {
    City {
        name,
        region,
        capital: false,
        lat,
        lon,
        aemet,
    }
}

